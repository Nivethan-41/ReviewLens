"""Pydantic data models and validation schemas for the ReviewLens REST API.

Defines request and response structures matching PRD.md Section 9 specification,
including review-level inputs/outputs, aggregate product reliability summaries,
and service health check payloads.
"""

from __future__ import annotations

from datetime import datetime
from typing import List, Optional
from pydantic import BaseModel, Field, field_validator


class ReviewIn(BaseModel):
    """Input payload schema for an individual product review."""

    id: Optional[str] = Field(
        default=None,
        description="Optional client-assigned review identifier. If omitted, the server generates one.",
    )
    text: str = Field(
        ...,
        min_length=1,
        max_length=5000,
        description="Review text body (must contain between 1 and 5000 characters).",
    )
    rating: Optional[float] = Field(
        default=None,
        ge=1.0,
        le=5.0,
        description="Optional star rating given by the reviewer (1 to 5).",
    )
    date: Optional[str] = Field(
        default=None,
        description="Optional ISO 8601 date string when review was posted (e.g. '2026-10-01').",
    )

    @field_validator("text")
    @classmethod
    def validate_non_empty_text(cls, v: str) -> str:
        """Ensure review text is not solely whitespace.

        Args:
            v: Input review text.

        Returns:
            Validated string.

        Raises:
            ValueError: If string is empty or contains only whitespace.
        """
        if not v.strip():
            raise ValueError("Review text cannot be empty or purely whitespace.")
        return v

    @field_validator("date")
    @classmethod
    def validate_iso_date(cls, v: Optional[str]) -> Optional[str]:
        """Validate that date is a valid ISO format string if provided.

        Args:
            v: Optional input date string.

        Returns:
            Validated ISO date string or None.

        Raises:
            ValueError: If date string cannot be parsed as ISO 8601 format.
        """
        if v is None:
            return None
        clean_v = v.strip()
        if not clean_v:
            return None
        try:
            datetime.fromisoformat(clean_v.replace("Z", "+00:00"))
        except Exception as exc:
            raise ValueError(
                f"Invalid date format: '{v}'. Expected ISO 8601 format (e.g. 'YYYY-MM-DD' or 'YYYY-MM-DDTHH:MM:SS')."
            ) from exc
        return clean_v


class AnalyzeRequest(BaseModel):
    """Request payload schema for review deception analysis."""

    page_url: Optional[str] = Field(
        default=None,
        description="Optional URL of the product page being analyzed.",
    )
    reviews: List[ReviewIn] = Field(
        ...,
        min_length=1,
        max_length=200,
        description="List of 1 to 200 product reviews to analyze.",
    )


class ReasonOut(BaseModel):
    """Explainability rationale explaining why a review was classified or flagged."""

    type: str = Field(
        ...,
        description="Category of indicator: 'language', 'style', or 'pattern'.",
    )
    text: str = Field(
        ...,
        description="Human-readable explanation of the detected indicator.",
    )


class ReviewResult(BaseModel):
    """Prediction result and explainability metadata for an individual review."""

    id: str = Field(
        ...,
        description="Review identifier matching input or auto-generated by the server.",
    )
    label: str = Field(
        ...,
        description="Classification outcome: 'suspicious', 'genuine', or 'uncertain'.",
    )
    confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Confidence score between 0.0 and 1.0.",
    )
    reasons: List[ReasonOut] = Field(
        default_factory=list,
        description="List of explainability rationale items for the classification.",
    )


class Summary(BaseModel):
    """Aggregate product-level reliability summary across all analyzed reviews."""

    total: int = Field(
        ...,
        ge=0,
        description="Total number of reviews analyzed.",
    )
    suspicious_count: int = Field(
        ...,
        ge=0,
        description="Number of reviews classified as suspicious.",
    )
    suspicious_pct: float = Field(
        ...,
        ge=0.0,
        le=100.0,
        description="Percentage of reviews classified as suspicious.",
    )
    reliability_score: int = Field(
        ...,
        ge=0,
        le=100,
        description="Product reliability score from 0 to 100.",
    )
    reliability_label: str = Field(
        ...,
        description="Categorical grade: 'High', 'Moderate', 'Low', or 'Not enough data'.",
    )
    insights: List[str] = Field(
        default_factory=list,
        description="List of human-readable insights explaining the reliability score.",
    )


class AnalyzeResponse(BaseModel):
    """Response payload schema for review deception analysis matching PRD Section 9."""

    results: List[ReviewResult] = Field(
        ...,
        description="Individual review evaluation results and explainability reasons.",
    )
    summary: Summary = Field(
        ...,
        description="Aggregate summary and reliability metrics.",
    )
    processing_ms: float = Field(
        default=0.0,
        ge=0.0,
        description="Server-side processing time in milliseconds.",
    )


class HealthResponse(BaseModel):
    """Response payload for the service health check endpoint."""

    status: str = Field(
        default="ok",
        description="Service health status indicator.",
    )
    model_version: str = Field(
        ...,
        description="Currently loaded model version string.",
    )
